print("=== Simple Calculator ===")

kesatu = int(float(input("Masukan angka Pertama: ")))
kedua = int(float(input("Masukan angka Kedua: ")))

#Penjumlahan
print(f"Hasil Penjumlahan: {kesatu + kedua}")

#Pengurangan 
print(f"Hasil Pengurangan: {kesatu - kedua}")

#Perkalian
print(f"Hasil Perkalian: {kesatu * kedua}")

#Pembagian 
print(f"Hasil Pembagian: {kesatu / kedua}")

#floor Division
print(f"Hasil Floor Division: {kesatu // kedua}")

#Modulus
print(f"Hasil Modulus: {kesatu % kedua}")

#Pangkat
print(f"Hasil Pangkat: {kesatu ** kedua}")